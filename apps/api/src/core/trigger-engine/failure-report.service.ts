import { Injectable, Logger } from '@nestjs/common';

import type { Run } from '@/core/task/entities/run.entity';
import type { Task } from '@/core/task/entities/task.entity';

import { StepExecutorService } from '@/core/actions/step-executor.service';
import { FoundryConfigService } from '@/core/foundry-config/foundry-config.service';
import { TaskService } from '@/core/task/task.service';

import type { IFailureMessage } from '@/core/actions/actions.types';
import type { IFailureContext, ITriggerConfig, TriggerKind } from '@/core/foundry-config/foundry-config.types';
import { triggerKindOf } from '@/core/foundry-config/trigger-kind';
import type { IRunJudgement } from '@/core/task/task.types';

export const COMMENT_TEXT_MAX_LENGTH = 4000;

const LOGGED_KINDS: Record<TriggerKind, string> = {
  issue: 'Issue',
  schedule: 'Scheduled',
  mergeRequest: 'Merge request',
};

@Injectable()
export class FailureReportService {
  private readonly logger = new Logger(FailureReportService.name);

  constructor(
    private readonly foundryConfigService: FoundryConfigService,
    private readonly taskService: TaskService,
    private readonly stepExecutorService: StepExecutorService
  ) {}

  logFailure(trigger: ITriggerConfig, task: Task, run: Run, judgement: IRunJudgement): void {
    const { error, deploymentFault } = judgement;
    const failed = `${LOGGED_KINDS[triggerKindOf(trigger)]} task ${task.id} failed ${this.whereFailed(trigger, run)}`;

    this.logger.error(
      {
        taskId: task.id,
        trigger: trigger.name,
        project: task.projectPath,
        issue: task.issueIid,
        fireTime: task.fireTime,
        mergeRequest: task.mergeRequestIid,
        runId: run.id,
        run: run.number,
        step: run.step,
        deploymentFault: deploymentFault ?? undefined,
        error: this.redact(trigger, error ?? 'No error was recorded'),
      },
      deploymentFault === null
        ? `logFailure(): ${failed}`
        : `logFailure(): Deployment fault: ${failed}, so its failureSteps do not run`
    );
  }

  /** Read from the run that failed the task, so a restart renders the same report. Rejects when it has none. */
  async context(trigger: ITriggerConfig, task: Task): Promise<IFailureContext> {
    const run = await this.taskService.findFailedRun(task.id);

    if (run === null) {
      throw new Error(`Task ${task.id} has no failed run to report`);
    }

    const errorText = this.truncate(this.redact(trigger, run.error ?? 'No error was recorded'));

    return {
      report: await this.report(trigger, task, run, errorText),
      reason: this.inlineCode(errorText.replaceAll(/\s+/g, ' ').trim()),
    };
  }

  /**
   * Says why the task failed and how to retry it, never quoting the transcript. Every piece of agent or error text sits
   * in a code fence, so GitLab runs no quick action and notifies no mention in it.
   */
  private async report(trigger: ITriggerConfig, task: Task, run: Run, errorText: string): Promise<string> {
    const step = trigger.steps.at(run.step);
    const message = step === undefined ? null : await this.stepExecutorService.failureMessage(step, run);
    const retryHint = this.retryHint(trigger);

    const body = [
      '# Failed',
      '',
      `:x: The \`${trigger.name}\` trigger gave up on ${this.subject(task)} ${this.whereFailed(trigger, run)}.`,
      '',
      '## Error',
      '',
      this.fence(errorText),
      ...this.messageBlock(trigger, message),
      ...(retryHint === null ? [] : ['', '## Retry', '', retryHint]),
      '',
      '---',
      `:robot: Generated by Swarmfoundry (${this.capitalise(trigger.name)}, task ${task.id})`,
    ].join('\n');

    return this.redact(trigger, body);
  }

  private messageBlock(trigger: ITriggerConfig, message: IFailureMessage | null): string[] {
    if (message === null) {
      return [];
    }

    if ('note' in message) {
      return ['', message.note];
    }

    return ['', `## ${message.heading}`, '', this.fence(this.truncate(this.redact(trigger, message.text)))];
  }

  private subject(task: Task): string {
    if (task.mergeRequestIid !== null) {
      return `merge request !${task.mergeRequestIid}`;
    }

    return task.fireTime === null ? 'this issue' : `its run for ${task.fireTime.toISOString()}`;
  }

  /** `run.number` counts the tries of the failed step. */
  private whereFailed(trigger: ITriggerConfig, run: Run): string {
    const runs = run.number === 1 ? '1 run' : `${run.number} runs`;

    return trigger.steps.length === 1
      ? `after ${runs}`
      : `at step ${run.step + 1} of ${trigger.steps.length}, after ${runs}`;
  }

  /**
   * Only an issue trigger fires again on a label, and its `failureSteps` may have added labels that block it. Clearing
   * one of its `notLabels` fires it once the issue matches, so the trigger labels need adding only where missing,
   * unless the step adding the flag failed.
   */
  private retryHint(trigger: ITriggerConfig): string | null {
    if (trigger.issue === undefined) {
      return null;
    }

    const { labels, notLabels } = trigger.issue;
    const added = [...new Set(trigger.failureSteps.flatMap(step => (step.kind === 'relabel' ? step.add : [])))].filter(
      label => !labels.includes(label)
    );
    const flags = added.filter(label => notLabels.includes(label));
    const quoted = (list: string[]) => list.map(label => `\`${label}\``).join(', ');

    const addBack =
      labels.length === 1
        ? `add ${quoted(labels)} again, removing it first if the issue still has it`
        : `add ${quoted(labels)} again, removing any the issue still has first`;

    if (flags.length > 0) {
      const addMissing =
        labels.length === 1
          ? `add ${quoted(labels)} if the issue lacks it`
          : `add any of ${quoted(labels)} the issue lacks`;
      const flagless = flags.length === 1 ? `lacks ${quoted(flags)}` : `has none of ${quoted(flags)}`;

      return `${this.capitalise(addMissing)}, then remove ${quoted(added)}. If the issue ${flagless}, instead ${addBack}.`;
    }

    return added.length === 0 ? `${this.capitalise(addBack)}.` : `Remove ${quoted(added)} and ${addBack}.`;
  }

  /**
   * Longer than any backtick run inside `text`, so the text cannot close it. Each line is indented, since GitLab finds
   * quick actions by a line-start `/` in the raw note and closes code blocks there on any line of three backticks.
   */
  private fence(text: string): string {
    const longest = this.longestBacktickRun(text);
    const fence = '`'.repeat(Math.max(3, longest + 1));
    const indented = text
      .split(/\r\n?|\n/)
      .map(line => ` ${line}`)
      .join('\n');

    return `${fence}text\n${indented}\n${fence}`;
  }

  /** One line, padded so a backtick at either end cannot join the delimiter. GitLab notifies no mention inside it. */
  private inlineCode(text: string): string {
    const delimiter = '`'.repeat(this.longestBacktickRun(text) + 1);

    return `${delimiter} ${text} ${delimiter}`;
  }

  private longestBacktickRun(text: string): number {
    return Math.max(0, ...(text.match(/`+/g) ?? []).map(backticks => backticks.length));
  }

  private capitalise(text: string): string {
    return `${text.charAt(0).toUpperCase()}${text.slice(1)}`;
  }

  private truncate(text: string): string {
    return text.length <= COMMENT_TEXT_MAX_LENGTH ? text : `${text.slice(0, COMMENT_TEXT_MAX_LENGTH)}...`;
  }

  private redact(trigger: ITriggerConfig, text: string): string {
    return this.foundryConfigService.redactText(
      text,
      this.stepExecutorService.secretsOf([...trigger.steps, ...trigger.failureSteps])
    );
  }
}
